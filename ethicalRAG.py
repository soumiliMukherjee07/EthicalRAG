def contains_protected_group(text):
    text = text.lower()
    return any(re.search(rf"\b{re.escape(term)}\b", text) for term in PROTECTED_GROUP_TERMS)


def rule_based_bias_reasons(prompt):
    text = prompt.lower()
    if not contains_protected_group(text):
        return []

    return [pattern for pattern in BIAS_CLAIM_PATTERNS if re.search(pattern, text)]


def get_semantic_bias_score(prompt):
    prompt_embedding = embedding_model.encode([prompt])
    similarities = cosine_similarity(prompt_embedding, bias_embeddings)[0]
    return float(np.max(similarities))


def get_calibrated_bias_risk(prompt, semantic_score, rule_reasons):
    """Converts detector evidence into a bounded, user-facing risk score."""
    text = prompt.lower()
    risk_score = semantic_score

    if rule_reasons:
        rule_boost = 0.72 + min(len(rule_reasons), 3) * 0.05
        risk_score = max(risk_score, rule_boost)

    severe_terms = [
        "less intelligent", "naturally better", "naturally worse", "superior",
        "inferior", "commit crimes", "criminal", "less capable",
        "harder to trust", "less suitable", "too slow", "lack the intelligence",
    ]
    if any(term in text for term in severe_terms):
        risk_score = max(risk_score, semantic_score + 0.18)

    benign_safety_terms = [
        "reduce bias", "gender bias", "accessibility", "inclusive",
        "support", "help", "programs", "protections", "guidelines",
        "screening", "discrimination", "founders", "web design",
        "statistical reports", "perceived as",
    ]
    if not rule_reasons and any(term in text for term in benign_safety_terms):
        risk_score -= 0.12

    risk_score = max(risk_score, 0.0)
    return min(risk_score, 0.94)


def get_bias_signals(prompt, threshold=BIAS_THRESHOLD):
    semantic_score = get_semantic_bias_score(prompt)
    rule_reasons = rule_based_bias_reasons(prompt)
    rule_triggered = len(rule_reasons) > 0
    risk_score = get_calibrated_bias_risk(prompt, semantic_score, rule_reasons)
    biased = risk_score >= threshold

    return {
        "biased": biased,
        "semantic_score": semantic_score,
        "risk_score": risk_score,
        "display_score": round(risk_score * 100, 2),
        "semantic_display_score": round(semantic_score * 100, 2),
        "rule_triggered": rule_triggered,
        "rule_reasons": rule_reasons,
    }


def get_bias_score(prompt):
    semantic_score = get_semantic_bias_score(prompt)
    rule_reasons = rule_based_bias_reasons(prompt)
    return get_calibrated_bias_risk(prompt, semantic_score, rule_reasons)


def detect_bias(prompt, threshold=BIAS_THRESHOLD):
    signals = get_bias_signals(prompt, threshold)
    return signals["biased"], signals["display_score"]

