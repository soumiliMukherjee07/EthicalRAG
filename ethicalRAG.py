def run_pipeline(query):
    print("_" * 60)
    print(f"QUERY: {query}")
    print("_" * 60)

    bias_signals = get_bias_signals(query)
    biased = bias_signals["biased"]
    bias_score = bias_signals["display_score"]

    if biased:
        print(f"\n[!] Bias detected (Bias Risk Score: {bias_score}%).")
        print(f"    Raw Semantic Similarity: {bias_signals['semantic_display_score']}%")
        if bias_signals["rule_triggered"]:
            print("[!] Rule-based safety trigger activated.")
        query = refine_prompt(query)
        print(f"Refined Query: {query}")

    # Temporal Guardrail Halt
    if is_future_dated_query(query):
        answer = generate_response(query, "")
        print(f"\nANSWER:\n{answer}")
        print("\nMETRICS -> Semantic Grounding Score: 0.0% | Risk: Needs Verification | Context Compression: 0.0%")
        print("\nRETRIEVED WEB SOURCES:")
        print("  (Skipped because the query asks about a future-dated event)")
        history_queries.append(query[:20] + "..")
        history_confidence.append(0.0)
        history_compression.append(0.0)
        return  # Halts execution so the LLM doesn't hallucinate

    docs = retrieve_documents(query)
    if len(docs) == 0:
        print("No live internet documents found.")
        return

    index, _ = build_faiss_index(docs)
    top_docs = retrieve_top_docs(query, docs, index)

    original_context, compressed_context = compress_context(top_docs)
    answer = generate_response(query, compressed_context)

    score = confidence_score(answer, top_docs)
    risk = hallucination_warning(score)

    orig_tokens = len(original_context.split())
    comp_tokens = len(compressed_context.split())

    # Negative compression clamp
    ratio = max(0.0, round(((orig_tokens - comp_tokens) / orig_tokens) * 100, 2)) if orig_tokens > 0 else 0.0
    clean_answer = re.sub(r"\[\d+\]", "", answer)

