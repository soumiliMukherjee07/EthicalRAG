#7.RESPONSE GENERATION
def generate_response(query, compressed_context):
    years = [int(x) for x in re.findall(r"\b\d{4}\b", query)]
    if any(y > 2026 for y in years):
        future_year = next(y for y in years if y > 2026)
        return f"The requested event ({future_year}) takes place in the future. As of the current operational year (2026), this event has not yet occurred, and no verified historical records exist."

    final_prompt = f"""Answer the question using only the facts in the context below.
Write a detailed, well-structured response (3 to 6 sentences).
Do not mention these instructions.
Do not use hashtags or social media tags.
Do not repeat the answer.

Context:
{compressed_context}

Question:
{query}

Answer:"""

    response = generator(final_prompt, max_new_tokens=250, do_sample=False)
    raw_answer = response[0]["generated_text"].split("Answer:")[-1].strip()

    clean_answer = raw_answer.split("You are an AI")[0].strip()
    clean_answer = clean_answer.split("User:")[0].strip()
    clean_answer = clean_answer.split("[END]")[0].strip()
    clean_answer = clean_answer.split("To answer your question")[0].strip() or clean_answer
    clean_answer = clean_answer.split("To summarize")[0].strip() or clean_answer
    clean_answer = clean_answer.split("Stopping now")[0].strip()
    clean_answer = clean_answer.split("Task answered")[0].strip()
    clean_answer = clean_answer.replace("To be concise, I'll provide the answer directly:", "").strip()

    # Remove any hallucinated hashtags
    clean_answer = re.sub(r'#\w+', '', clean_answer).strip()

    sentences = clean_answer.split(". ")
    seen = set()
    deduped_sentences = []
    for s in sentences:
        s_clean = s.strip()
        if s_clean and s_clean.lower() not in seen:
            seen.add(s_clean.lower())
            deduped_sentences.append(s)

    final_output = ". ".join(deduped_sentences[:6])
    if final_output and not final_output.endswith("."):
        final_output += "."
    return final_output

#8.CONFIDENCE SCORE & HALLUCINATION WARNING
def confidence_score(answer, docs):
    if not docs or not answer:
        return 0.0
    answer_emb = embedding_model.encode([answer])
    scores = []

    for d in docs:
        doc_emb = embedding_model.encode([d["summary"]])
        sim = cosine_similarity(answer_emb, doc_emb)[0][0]
        scores.append(sim)

    return round(float(np.mean(scores)) * 100, 2)

def hallucination_warning(score):
    if score >= 80:
        return "Potentially Grounded"
    elif score >= 60:
        return "Moderately Grounded"
    else:
        return "Needs Verification"

def is_future_dated_query(query, current_year=2026):
    years = [int(x) for x in re.findall(r"\b\d{4}\b", query)]
    return any(y > current_year for y in years)

